CREATE TABLE room (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id BIGINT NOT NULL REFERENCES hotel(id),
    number VARCHAR(30) NOT NULL,
    beds INTEGER NOT NULL CHECK (beds > 0),
    price DECIMAL(12, 2) NOT NULL CHECK (price >= 0),
    state INTEGER NOT NULL,
    CONSTRAINT ck_room_state CHECK (state IN (0, 1, 2)),
    UNIQUE (hotel_id, number)
);

CREATE TABLE room_equipment (
    room_id BIGINT NOT NULL REFERENCES room(id),
    equipment_code INTEGER NOT NULL,
    CONSTRAINT ck_equipment_code CHECK (equipment_code IN (0, 1, 2, 3)),
    PRIMARY KEY (room_id, equipment_code)
);

CREATE TABLE booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES room(id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status INTEGER NOT NULL,
    CONSTRAINT ck_booking_status CHECK (status IN (0, 1, 2, 3)),
    CHECK (end_date > start_date)
);
CREATE INDEX ix_booking_dates ON booking(room_id, status, start_date, end_date);

CREATE TABLE stay (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES room(id),
    booking_id BIGINT UNIQUE REFERENCES booking(id),
    checked_in_at TIMESTAMP WITH TIME ZONE NOT NULL,
    checked_out_at TIMESTAMP WITH TIME ZONE,
    price DECIMAL(12, 2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE revenue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_id BIGINT NOT NULL UNIQUE REFERENCES stay(id),
    hotel_id BIGINT NOT NULL REFERENCES hotel(id),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    nights BIGINT NOT NULL CHECK (nights >= 1),
    amount DECIMAL(14, 2) NOT NULL CHECK (amount >= 0)
);
