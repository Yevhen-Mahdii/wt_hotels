-- Enum codes are stable application identifiers, never ordinal positions.
CREATE TABLE hotel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    address VARCHAR(250) NOT NULL
);

CREATE TABLE app_role (
    code INTEGER PRIMARY KEY,
    name VARCHAR(40) NOT NULL UNIQUE,
    label VARCHAR(80) NOT NULL
);
CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(180) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role INTEGER NOT NULL REFERENCES app_role(code),
    hotel_id BIGINT REFERENCES hotel(id),
    CONSTRAINT ck_user_role CHECK (role IN (0, 1, 2)),
    CONSTRAINT ck_user_hotel CHECK (
        (role = 2 AND hotel_id IS NOT NULL)
        OR (role <> 2 AND hotel_id IS NULL)
    )
);

